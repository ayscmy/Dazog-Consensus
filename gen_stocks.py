for _x in S:
    if _x["type"] in ("stock", "etf"):
        _dg = _re.sub(r"\D", "", _x["code"])
        if _dg.startswith("51"): _p = "sh"
        elif _dg.startswith("15"): _p = "sz"
        elif _dg[0] == "6": _p = "sh"
        elif _dg[0] in "023": _p = "sz"
        elif _dg[0] == "9": _p = "sh"
        else: _p = "sh"
        _x["code"] = _p + _dg

